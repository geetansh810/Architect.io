// ─── Helper Functions ─────────────────────────────────────────────────
function getNodeLabel(node) {
  return node.data?.label || node.data?.name || formatNodeType(node.type);
}

function sanitizeId(id) {
  return String(id).replace(/[^a-zA-Z0-9_]/g, '_');
}

function getComplexityRating(stats) {
  if (stats.totalNodes <= 3) return '🟢 Simple (MVP / prototype)';
  if (stats.totalNodes <= 8) return '🟡 Moderate (early-stage production)';
  if (stats.totalNodes <= 15) return '🟠 Complex (requires careful orchestration)';
  return '🔴 Enterprise-scale (requires DevOps expertise)';
}

function getScaleEstimate(stats) {
  if (stats.totalNodes <= 3) return 'small teams and prototypes (~100 concurrent users)';
  if (stats.totalNodes <= 8) return 'early-stage products (~1,000 concurrent users)';
  return 'mid-scale production (~10,000+ concurrent users with proper infrastructure)';
}

function getMermaidShape(nodeType) {
  const shapes = {
    apiNode: { open: '[/', close: '/]' },
    authNode: { open: '[/', close: '/]' },
    loadBalancerNode: { open: '[(', close: ')]' },
    dbNode: { open: '[(', close: ')]' },
    cacheNode: { open: '((', close: '))' },
    queueNode: { open: '[/', close: '/]' },
    entityNode: { open: '[', close: ']' },
    logicNode: { open: '{', close: '}' },
  };
  return shapes[nodeType] || { open: '[', close: ']' };
}

function getNodeEmoji(type) {
  const map = {
    apiNode: '🔀', authNode: '🔐', entityNode: '📋',
    dbNode: '🗄️', cacheNode: '⚡', storageNode: '🪣',
    queueNode: '📨', mailNode: '📧', logicNode: '🧠',
    middlewareNode: '🔧', cronNode: '⏱️', webhookNode: '🔗',
    loadBalancerNode: '⚖️', cdnNode: '🌐', replicaNode: '📑',
    counterServiceNode: '🔢',
  };
  return map[type] || '📦';
}

function formatNodeType(type) {
  const map = {
    apiNode: 'API Endpoint', authNode: 'Auth Service', entityNode: 'Data Entity',
    dbNode: 'Database', cacheNode: 'Cache (Redis)', storageNode: 'Object Storage',
    queueNode: 'Message Queue', mailNode: 'Mail Service', logicNode: 'Business Logic',
    middlewareNode: 'Middleware', cronNode: 'Cron Job', webhookNode: 'Webhook',
    loadBalancerNode: 'Load Balancer', cdnNode: 'CDN', replicaNode: 'Replica',
    counterServiceNode: 'Counter Service',
  };
  return map[type] || (type ? type.replace(/Node$/, '').replace(/([A-Z])/g, ' $1').trim() : 'Component');
}

function getNodeFlowDescription(node, sources, targets, analysis) {
  const label = getNodeLabel(node);
  const srcStr = sources.length ? `from **${sources.join(', ')}**` : 'as an entry point';
  const tgtStr = targets.length ? `forwards to **${targets.join(', ')}**` : 'and terminates (no downstream)';

  const descriptions = {
    apiNode: `Receives HTTP requests ${srcStr}. Validates input, applies middleware, and ${tgtStr}.${node.data?.authEnabled ? ' Requires authentication.' : ''}`,
    authNode: `Handles authentication ${srcStr}. Issues/validates JWT tokens and ${tgtStr}.`,
    entityNode: `Defines the **${label}** data model ${srcStr}. Schema drives generated routes, controllers, and models. ${tgtStr}.`,
    dbNode: `Persists data ${srcStr}. ${node.data?.type === 'postgresql' ? 'Uses PostgreSQL with relational schema.' : 'Uses MongoDB with flexible document schema.'} ${tgtStr}.`,
    cacheNode: `Intercepts repeated queries ${srcStr}. Serves cached responses to reduce database load. ${tgtStr}.`,
    queueNode: `Buffers messages ${srcStr} for asynchronous processing. Decouples producers from consumers. ${tgtStr}.`,
    logicNode: `Executes business logic ${srcStr}. Applies transformation, validation, or computation. ${tgtStr}.`,
    middlewareNode: `Intercepts requests ${srcStr}. Applies cross-cutting concerns (logging, rate limiting, etc.). ${tgtStr}.`,
    mailNode: `Sends transactional emails triggered ${srcStr}. ${tgtStr}.`,
    storageNode: `Handles file upload/retrieval ${srcStr}. Stores objects in S3-compatible storage. ${tgtStr}.`,
    cronNode: `Runs scheduled tasks on a defined interval. Not triggered by requests — operates independently. ${tgtStr}.`,
    webhookNode: `Receives external event callbacks ${srcStr}. Validates payload and ${tgtStr}.`,
    loadBalancerNode: `Distributes incoming traffic ${srcStr} across multiple backend instances. ${tgtStr}.`,
    cdnNode: `Caches and serves static assets or API responses at the edge ${srcStr}. Reduces latency for geographically distributed users. ${tgtStr}.`,
    replicaNode: `Provides a read replica ${srcStr}. Offloads read queries from the primary database. ${tgtStr}.`,
    counterServiceNode: `Maintains atomic counters or rate-limit state ${srcStr}. ${tgtStr}.`,
  };

  return descriptions[node.type] || `Acts as a **${formatNodeType(node.type)}** component ${srcStr}. ${tgtStr}.`;
}

function getNodeRoleDescription(node, analysis) {
  const inCount = (analysis.incoming[node.id] || []).length;
  const outCount = (analysis.outgoing[node.id] || []).length;
  const isEntry = inCount === 0;
  const isTerminal = outCount === 0;

  if (isEntry && isTerminal) return `Standalone component — no upstream or downstream connections.`;
  if (isEntry) return `**Entry point** — initiates the data flow for this architecture.`;
  if (isTerminal) return `**Terminal node** — final destination for data in this flow.`;
  if (inCount + outCount > 4) return `**Hub node** — central to the architecture with high connectivity. Critical for reliability.`;
  return `Intermediary component bridging upstream and downstream layers.`;
}

